const SCALE = 3;
const GLYPH_W = 6 * SCALE; // 5 columns + 1 spacing
const LINE_H = 10 * SCALE; // 7 rows + 3 spacing
const MARGIN = 20;

/** The text a reader of the image sees (upper case, accents and unknown characters dropped). */
export function pngVisibleText(line: string): string {
  return line
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toUpperCase()
    .split('')
    .filter((c) => c in FONT)
    .join('');
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf: Buffer): number {
  let c = 0xffffffff;
  for (const b of buf) c = (CRC_TABLE[(c ^ b) & 0xff] ?? 0) ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

/** Renders the lines as a grayscale PNG. */
export function buildSyntheticPng(lines: readonly string[]): Buffer {
  const texts = lines.map(pngVisibleText);
  const width = MARGIN * 2 + Math.max(1, ...texts.map((t) => t.length)) * GLYPH_W;
  const height = MARGIN * 2 + Math.max(1, texts.length) * LINE_H;
  const pixels = Buffer.alloc(width * height, 0xff);
  texts.forEach((text, row) => {
    [...text].forEach((ch, col) => {
      const glyph = FONT[ch] ?? FONT[' ']!;
      glyph.forEach((bits, gy) => {
        [...bits].forEach((bit, gx) => {
          if (bit !== '1') return;
          for (let dy = 0; dy < SCALE; dy++) {
            for (let dx = 0; dx < SCALE; dx++) {
              const x = MARGIN + col * GLYPH_W + gx * SCALE + dx;
              const y = MARGIN + row * LINE_H + gy * SCALE + dy;
              pixels[y * width + x] = 0x00;
            }
          }
        });
      });
    });
  });
  // Each scanline starts with filter type 0 (none).
  const raw = Buffer.alloc((width + 1) * height);
  for (let y = 0; y < height; y++)
    pixels.copy(raw, y * (width + 1) + 1, y * width, (y + 1) * width);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr.writeUInt8(8, 8); // bit depth
  ihdr.writeUInt8(0, 9); // grayscale
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
